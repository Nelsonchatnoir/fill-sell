async function etat() {
  const f = await q(`SELECT p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' AS k, md5(pg_get_functiondef(p.oid)) AS m,
      coalesce(p.proacl::text, '') AS acl, p.prosecdef AS sd, coalesce(p.proconfig::text, '') AS cfg, p.provolatile AS v
    FROM pg_proc p WHERE p.pronamespace = 'public'::regnamespace`);
  return Object.fromEntries(f.map((r) => [r.k, { m: r.m, reste: `${r.acl}|${r.sd}|${r.cfg}|${r.v}` }]));
}
const ecart = (a, b) => {
  const cles = [...new Set([...Object.keys(a), ...Object.keys(b)])];
  return { ajoutes: cles.filter((k) => !(k in a)), retires: cles.filter((k) => !(k in b)),
    changes: cles.filter((k) => k in a && k in b && a[k].m !== b[k].m), droits: cles.filter((k) => k in a && k in b && a[k].reste !== b[k].reste) };
};

