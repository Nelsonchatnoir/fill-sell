const id = (s) => `"${String(s).replace(/"/g, '""')}"`;

async function decor(c) {
  const echecs = [];
  const essayer = async (sql, quoi) => { try { await c.query(sql); return true; } catch (e) { echecs.push(`${quoi} : ${e.message}`); return false; } };
  await c.query(PRELUDE);
  // Les séquences des colonnes `nextval('…'::regclass)` (coin_ledger.id, …).
  for (const s of new Set(FX.tables.flatMap((t) => t.cols.map((k) => /nextval\('([^']+)'/.exec(k.d ?? '')?.[1]).filter(Boolean)))) {
    await essayer(`CREATE SEQUENCE IF NOT EXISTS public.${id(s.replace(/^public\./, '').replace(/"/g, ''))}`, `séquence ${s}`);
  }
  for (const t of FX.tables) {
    const cols = t.cols.filter((k) => !k.g).map((k) => `${id(k.n)} ${k.t}${k.id === 'a' ? ' GENERATED ALWAYS AS IDENTITY' : k.id === 'd' ? ' GENERATED BY DEFAULT AS IDENTITY' : ''}`);
    await essayer(`CREATE TABLE public.${id(t.nom)} (${cols.join(', ')})`, `table ${t.nom}`);
    for (const k of t.cols.filter((x) => x.d && !x.id && !x.g)) await essayer(`ALTER TABLE public.${id(t.nom)} ALTER COLUMN ${id(k.n)} SET DEFAULT ${k.d}`, `défaut ${t.nom}.${k.n}`);
    for (const k of t.cons) await essayer(`ALTER TABLE public.${id(t.nom)} ADD CONSTRAINT ${id(k.n)} ${k.def}`, `contrainte ${t.nom}.${k.n}`);
  }
  await c.query('SET check_function_bodies = off');
  let nf = 0;
  for (const f of FX.fonctions) {
    if (!(await essayer(f.def, `fonction ${f.nom}`))) continue;
    nf++;
    // Les droits EXECUTE de prod, exacts.
    await c.query(`REVOKE ALL ON FUNCTION public.${id(f.nom)}(${f.args}) FROM PUBLIC, anon, authenticated, service_role`);
    for (const m of String(f.acl).replace(/^\{|\}$/g, '').split(',').filter(Boolean)) {
      const [role, reste] = m.split('=');
      if (['anon', 'authenticated', 'service_role'].includes(role) && reste.split('/')[0].includes('X')) await c.query(`GRANT EXECUTE ON FUNCTION public.${id(f.nom)}(${f.args}) TO ${role}`);
    }
  }
  await c.query('SET check_function_bodies = on');
  for (const l of FX.config.coin_config) await c.query('INSERT INTO public.coin_config (key, value) VALUES ($1, $2)', [l.key, l.value]);
  return { echecs, nf };
}

